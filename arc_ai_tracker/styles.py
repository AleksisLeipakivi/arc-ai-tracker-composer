def style_scale(style: str, mood_mode: tuple[int, ...]) -> tuple[int, ...]:
    """Return the preset's major/minor mode, keeping explicit dark mood minor."""
    selected = STYLES[style]
    if mood_mode == (0, 2, 3, 5, 7, 8, 10) or selected.mode == "minor":
        return (0, 2, 3, 5, 7, 8, 10)
    return (0, 2, 4, 5, 7, 9, 11)
